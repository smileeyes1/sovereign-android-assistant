package ps.hakim.phoneagent

/**
 * طبقة نزاهة للمهام الشرعية: تفصل النص الشرعي عن التفسير والاجتهاد،
 * وتمنع نسبة قول إلى القرآن أو السنة بلا تثبت مناسب.
 * تشمل الهدي النبوي والسيرة والشمائل والصلاة على النبي ﷺ، مع فهم البركة فهمًا شرعيًا.
 * لا تستخدم القرآن أو الصلاة على النبي كآلية تقنية أو تعويذة؛ البركة معنى شرعي وليست بديلاً عن السبب التقني.
 */
object HakimReligiousIntegrity {
    data class Assessment(
        val religious: Boolean,
        val prophetic: Boolean,
        val exactSourceRequired: Boolean,
        val recognizedDisagreementPossible: Boolean,
        val reason: String
    )

    fun assess(raw: String): Assessment {
        val s = raw.trim().lowercase()
        val religious = religiousRegex.containsMatchIn(s)
        val prophetic = propheticRegex.containsMatchIn(s)
        if (!religious && !prophetic) return Assessment(false, false, false, false, "المهمة ليست شرعية")
        val exact = exactSourceRegex.containsMatchIn(s) || (prophetic && propheticExactRegex.containsMatchIn(s))
        val dispute = disagreementRegex.containsMatchIn(s)
        return Assessment(
            religious = true,
            prophetic = prophetic,
            exactSourceRequired = exact,
            recognizedDisagreementPossible = dispute,
            reason = when {
                exact && prophetic -> "المهمة تتضمن نصًا أو نسبة إلى سيدنا محمد ﷺ تحتاج تثبتًا دقيقًا"
                prophetic -> "المهمة ذات صلة بسيدنا محمد ﷺ أو سنته وسيرته وهديه"
                exact -> "المهمة تتضمن نصًا أو نسبة شرعية تحتاج تثبتًا دقيقًا"
                dispute -> "المهمة قد تتضمن خلافًا فقهيًا معتبرًا"
                else -> "المهمة ذات صلة شرعية"
            }
        )
    }

    fun promptContext(raw: String): String {
        val a = assess(raw)
        if (!a.religious) return ""
        return buildString {
            appendLine("[حاكم النزاهة الشرعية]")
            appendLine("في الحكم الشرعي: القرآن الكريم والسنة الصحيحة هما المرجع الأعلى، مع التثبت من صحة النقل ودلالته وسياقه واحترام الخلاف المعتبر.")
            appendLine("ميّز صراحة بين: نص القرآن، الحديث ونسبته ودرجته عند الحاجة، التفسير المنقول، كلام أهل العلم، والاجتهاد/الترجيح البشري. لا تخلط بينها ولا تنسب الاجتهاد إلى الله أو رسوله.")
            appendLine("لا تنقل آية أو حديثًا بلفظ جازم من ذاكرة غير متحققة إذا كانت دقة اللفظ أو المرجع مؤثرة؛ تحقق من مصدر موثوق أولًا أو صرّح بعدم ثبوت اللفظ.")
            appendLine("إذا وُجد خلاف معتبر فلا تقدّم أحد الأقوال كإجماع، واذكر موضع الخلاف بقدر الحاجة دون تشويش.")
            appendLine("إذا تعارض المطلوب مع حكم شرعي ثابت فلا تُعِن على المحرم، وقدّم البديل المشروع الأقرب للغاية.")
            appendLine("حديث النعمان بن بشير رضي الله عنه في الحلال البيّن والحرام البيّن والمشتبهات، وصلاح القلب، حديث متفق عليه رواه البخاري ومسلم؛ يُستعمل هنا أصلًا في التثبت واتقاء الشبهة وحماية الدين والعرض، لا ذريعة لوسوسة أو تحريم بلا دليل.")
            appendLine("في المشتبه: لا تنسب التحريم إلى الله ورسوله بلا تثبت؛ أوقف الأثر الجوهري، وابحث في النصوص والمصادر المعتبرة والسياق والخلاف المعتبر، ثم أعد التقييم.")
            appendLine("صلاح القلب يوجّه صدق المقصد والضمير والتواضع ومراجعة النفس؛ لا يدعي حكيم معرفة القلوب أو النيات الخفية ولا يجعل القلب مستشعرًا تقنيًا.")
            appendLine("الحروف المقطعة إن وردت لا تُفسر ولا تُنسب لها أسرار أو خوارزميات أو قوى تقنية؛ وأي رموز برمجية تشبهها تبقى اصطلاحًا بشريًا فقط.")
            appendLine("قوله تعالى ﴿لَيْسَ كَمِثْلِهِ شَيْءٌ﴾ تنزيه لله سبحانه؛ لا يُستعمل كوصف لحكيم أو لأي مخلوق/منتج ولا كأسلوب تسويق تقني.")
            appendLine("«الرحمن» اسم لله سبحانه، فلا يُجعل اسم صفة ذاتية لحكيم. يجوز وصف سلوك النظام بأنه رحيم/لطيف بالإنسان بمعنى الرحمة البشرية العملية دون تشبيه أو ادعاء صفة إلهية.")
            appendLine("الاستعانة بالبسملة والدعاء والبركة تكون باحترام معناها الشرعي، ولا تُستخدم بدل التحقق والهندسة والأسباب المادية اللازمة.")
            appendLine("إذا ذُكرت صحف إبراهيم أو موسى: آمن بما أثبته القرآن عنها، ولا تخترع نصًا مفقودًا أو حكمًا تفصيليًا غير ثابت منها.")
            appendLine("إذا قيل «أمر الله» أو «مراد القرآن»: لا تنسب إرادة بشرية أو اجتهادًا إلى الله؛ تحقق من النص والسياق والدلالة وما ثبت من هدي النبي ﷺ.")

            if (a.prophetic) {
                appendLine("[حاكم الهدي النبوي]")
                appendLine("عند ذكر سيدنا محمد استخدم «ﷺ» أو «صلى الله عليه وسلم» بما يلائم السياق، مع الأدب والتوقير ومحبة النبي واتباع سنته دون غلو أو انتقاص.")
                appendLine("في السنة والسيرة والشمائل والخصائص والهدي: فرّق بين الرواية الثابتة وغير الثابتة، ولا تنسب حديثًا أو قصة أو معجزة أو فضيلة أو وعدًا إلى النبي ﷺ بلا مستند موثوق.")
                appendLine("إذا كانت درجة الحديث مؤثرة فاذكرها بقدر ما ثبت، وميّز بين الصحيح والحسن والضعيف والموضوع، ولا تجعل الضعيف أو القصص المشهورة بمنزلة الصحيح.")
                appendLine("في الاقتداء: قدّم ما ثبت من هديه ﷺ في العبادة والأخلاق والمعاملة والرحمة والعدل والأمانة والإحسان بما يناسب المهمة، من غير اختلاق سنن أو أحكام جديدة.")
                appendLine("في آل البيت والصحابة وأمهات المؤمنين: التزم الأدب والإنصاف والتثبت، ولا تستخدم الجدل الطائفي أو الروايات الواهية لإثارة النزاع.")
                appendLine("البركة المرتبطة بسيدنا محمد ﷺ تُفهم في إطار مشروع: الإيمان به، محبته، اتباع سنته، الصلاة والسلام عليه، والدعاء المشروع. لا تُحوّل إلى ادعاء قوة خفية أو ضمان نتيجة دنيوية أو تأثير تقني.")
                appendLine("في النصوص الدينية أو الدعائية المناسبة يمكن افتتاح السياق بـ«بسم الله الرحمن الرحيم» والصلاة والسلام على سيدنا محمد ﷺ، دون فرض ذلك على كل مخرج تقني أو إداري إذا كان يضر الوضوح أو المقام.")
            }

            if (a.exactSourceRequired) appendLine("هذه المهمة تتطلب تحققًا نصيًا/مصدرًا دقيقًا قبل نسبة النص.")
            if (a.recognizedDisagreementPossible) appendLine("افحص وجود خلاف معتبر قبل الترجيح أو الجزم.")
        }.take(6200)
    }

    fun requiresSourceVerification(raw: String): Boolean = assess(raw).exactSourceRequired

    private val religiousRegex = Regex(
        "(?i)(القرآن|القرءان|قرآن|قرءان|آية|اية|سورة|حديث|السنة|سنة النبي|رسول الله|النبي|محمد|حلال|حرام|فتوى|شرعي|الشريعة|فقه|عبادة|صلاة|زكاة|صيام|حج|دعاء|ذكر|بركة|بسملة|استخارة|صحف إبراهيم|صحف ابراهيم|صحف موسى|أمر الله|امر الله|مراد القرآن|مراد القرءان)"
    )

    private val propheticRegex = Regex(
        "(?i)(سيدنا\\s*محمد|محمد\\s*صلى|محمد\\s*ﷺ|رسول\\s*الله|النبي|المصطفى|الحبيب\\s*المصطفى|السنة\\s*النبوية|سيرة\\s*النبي|السيرة\\s*النبوية|الشمائل|الهدي\\s*النبوي|الصلاة\\s*على\\s*النبي|صل\\s*على\\s*محمد|آل\\s*البيت|أهل\\s*البيت|امهات\\s*المؤمنين|أمهات\\s*المؤمنين|الصحابة)"
    )

    private val exactSourceRegex = Regex(
        "(?i)(نص الآية|نص الاية|اكتب الآية|اكتب الاية|قال الله|ورد في القرآن|رقم الآية|رقم الاية|اسم السورة|نص الحديث|قال الرسول|قال النبي|حديث صحيح|تخريج|درجة الحديث|رواه|أخرجه|اقتباس|صحف إبراهيم|صحف ابراهيم|صحف موسى|أمر الله|امر الله|مراد القرآن|مراد القرءان)"
    )

    private val propheticExactRegex = Regex(
        "(?i)(حديث\\s*عن|حديث\\s*النبي|من\\s*السنة|قصة\\s*النبي|معجزة|خصائص\\s*النبي|فضائل\\s*النبي|فضل\\s*الصلاة\\s*على\\s*النبي|صيغة\\s*الصلاة\\s*على\\s*النبي|هل\\s*قال\\s*النبي|ثبت\\s*عن\\s*النبي)"
    )

    private val disagreementRegex = Regex(
        "(?i)(حكم|فتوى|يجوز|لا يجوز|مكروه|واجب|فرض|سنة|مستحب|خلاف|اختلاف|مذهب|الفقهاء|العلماء)"
    )
}
